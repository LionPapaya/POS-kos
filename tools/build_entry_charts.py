"""Build static entry chart variants and their matching kOS coordinate catalog.

Requires Pillow. Run from any directory; flight software never runs this tool.
The historical reference is reprojected, not shifted independently of its axes.
"""
from pathlib import Path
import json
import re
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / 'Script/Libraries/Poseidon_SSTO'
ASSETS = ROOT / 'Script/Libraries/gui_images/entry_charts'
PROFILE = (LIB / 'entry_nominal_profile.ks').read_text()

def values(name):
    return [float(x) for x in re.search(r'global '+name+r' is list\(([^)]+)\)', PROFILE)[1].split(',')]

def build():
    ASSETS.mkdir(exist_ok=True)
    energies = values('entry_nominal_energy_samples')
    ranges = values('entry_nominal_range_samples')
    widths = values('entry_nominal_corridor_samples')
    # Fixed energy-phase boundaries; extra first-page ceilings support higher orbits.
    energy_windows = [[(260000,x) for x in (290000,340000,420000,600000,1000000)],
                      [(210000,260000)],[(170000,210000)],[(140000,170000)],[(0,140000)]]
    range_widths = [500000,350000,450000,250000,180000]
    fallback_tops = [1100000,800000,600000,300000,180000]
    try:
        font = ImageFont.truetype('DejaVuSans.ttf', 12)
    except OSError:
        font = ImageFont.truetype('C:/Windows/Fonts/arial.ttf', 12)
    catalog=[]
    for page, energy_choices in enumerate(energy_windows,1):
        page_choices=[]
        for emin,emax in energy_choices:
            range_choices=[(r,r+range_widths[page-1]) for r in range(0,1500001,100000)]
            range_choices += [(0,fallback_tops[page-1]),(0,1000000),(0,2000000)]
            for rmin,rmax in sorted(set(range_choices),key=lambda r:(r==(0,2000000),r)):
                asset=f'p{page}_e{emin//1000}_{emax//1000}_r{rmin//1000}_{rmax//1000}.png'
                record=dict(number=page,energy_min=emin,energy_max=emax,range_min=rmin,range_max=rmax,
                            image='Libraries/gui_images/entry_charts/'+asset)
                page_choices.append(record)
                image=Image.new('RGB',(640,280),(22,29,33));draw=ImageDraw.Draw(image)
                xy=lambda e,r:(52+568*(e-emin)/(emax-emin),232-208*(r-rmin)/(rmax-rmin))
                # Clip reference geometry to the calibrated plot rectangle.
                reference=Image.new('RGB',(640,280),(22,29,33));rd=ImageDraw.Draw(reference)
                band=[xy(e,r+w) for e,r,w in zip(energies,ranges,widths)]
                band += [xy(e,r-w) for e,r,w in reversed(list(zip(energies,ranges,widths)))]
                rd.polygon(band,fill=(38,49,56))
                rd.line([xy(e,r) for e,r in zip(energies,ranges)],fill=(139,153,161),width=1)
                image.paste(reference.crop((52,24,621,233)),(52,24))
                for tick in range(5):
                    x=52+568*tick/4;y=232-208*tick/4
                    draw.line((x,24,x,232),fill=(71,85,94))
                    draw.line((52,y,620,y),fill=(71,85,94))
                    draw.text((x,240),f'{(emin+(emax-emin)*tick/4)/1000:g}',font=font,fill=(193,204,210),anchor='mt')
                    draw.text((43,y),f'{(rmin+(rmax-rmin)*tick/4)/1000:g}',font=font,fill=(193,204,210),anchor='rm')
                draw.text((52,5),'RANGE TO TAEM (km)',font=font,fill=(193,204,210))
                draw.text((620,262),'ENERGY HEIGHT (km)',font=font,fill=(193,204,210),anchor='rt')
                image.save(ASSETS/asset,optimize=True)
        catalog.append(page_choices)
    header='// Generated by tools/build_entry_charts.py. Bounds and PNG axes are one contract.\n'
    lines=[header,'global entry_chart_catalog is list(']
    for pi, choices in enumerate(catalog):
        lines.append('    list(')
        for ci,c in enumerate(choices):
            fields=','.join('"'+k+'",'+('"'+v+'"' if isinstance(v,str) else str(v)) for k,v in c.items())
            lines.append('        lex('+fields+')'+(',' if ci+1<len(choices) else ''))
        lines.append('    )'+(',' if pi+1<len(catalog) else ''))
    lines.append(').\n')
    (LIB/'entry_chart_catalog.ks').write_text('\n'.join(lines),encoding='utf-8')
    (ASSETS/'catalog.json').write_text(json.dumps(catalog,indent=2)+'\n')
    print(f'Generated {sum(map(len,catalog))} charts and coordinate catalog')

if __name__=='__main__':
    build()
